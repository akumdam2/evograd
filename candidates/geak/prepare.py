#!/usr/bin/env python3
"""Build a GEAK ``kernel_workflow`` op task dir (author mode) from an adbench-tools task.

    python candidates/geak/prepare.py --task TASK --run-dir RUN --out OP_TASK_DIR

GEAK's author mode takes "an op task dir holding the IMMUTABLE oracle
(``meta.json`` + ``unittest.py`` + frozen ``baseline_src/``)" and writes a
from-scratch implementation into ``kernel_src/``. This writes that dir with
evograd as the oracle:

    meta.json              op spec: kind, shapes, dtype, math contract, regime,
                           cases, baseline_callable, the candidate entry
    unittest.py            IMMUTABLE. Runs `python -m evograd.adbench_tools
                           evaluate` on kernel_src/candidate.py (correctness and
                           timing; --correctness for correctness only), logs to
                           the run's ledger, prints GEAK_RESULT_LATENCY_MS lines
    baseline_src/          the frozen baseline: one eager PyTorch autograd step
                           of the runtime reference, the speedup denominator
    TASK.md                the shared problem statement
    adbench_primitives.py   granted primitives, importable standalone
    kernel_src/            empty; GEAK writes kernel_src/candidate.py
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

ENTRY = "kernel_src/candidate.py"


def meta(task, run_dir: Path) -> dict:
    spec = task.spec
    abi = spec["abi"]
    return {
        "op_kind": spec.get("family") or task.op_name,
        "kernel_name": task.op_name,
        "target_language": "triton",
        "dtype": spec["workload"]["dtype"],
        "shapes": {entry["name"]: entry.get("size") for entry in abi["arguments"] + abi["outputs"]},
        "math_contract": (f"{spec['semantics']['forward']}\nBACKWARD: "
                          f"{spec['semantics']['backward']}"),
        "regime": "training: one forward+backward step (forward_with_saved, then backward_from_saved)",
        "cases": [{"id": spec["task_id"], "dims": spec["workload"]["dims"],
                   "dtype": spec["workload"]["dtype"], "weight": 1.0}],
        "baseline_callable": "baseline_src/reference_step.py:reference_step",
        "baseline_note": ("eager PyTorch autograd on the runtime reference, the evograd "
                          f"evaluator's `{spec['performance_baseline']}` baseline"),
        "entry": {"file": ENTRY, "functions": [abi["forward_fn"], abi["backward_fn"]],
                  "forward_signature": abi["forward_signature"],
                  "backward_signature": abi["backward_signature"]},
        "build": False,
        "oracle": "evograd.adbench_tools (unittest.py); its verdict and timing are final",
        "evograd_task": str(task.root),
        "evograd_run": str(run_dir),
        "statement": "TASK.md",
    }


def unittest_source(task, run_dir: Path) -> str:
    return f'''#!/usr/bin/env python3
"""IMMUTABLE oracle for GEAK (generated by evograd adbench-tools). Do not edit.

Candidate: {ENTRY} (relative to the workspace you run this from), a Python
module defining the pair in TASK.md. Run from the workspace:

    python3 unittest.py               # correctness + timing (the score)
    python3 unittest.py --correctness # correctness only

Correctness and timing come from the evograd evaluator; the baseline is eager
PyTorch autograd of the reference (baseline_src/). Exit 0 iff correct.
"""
import json
import subprocess
import sys
from pathlib import Path

TASK = {str(task.root)!r}
RUN = {str(run_dir)!r}
PYTHON = {sys.executable!r}

here = Path(__file__).resolve().parent
candidate = Path.cwd() / {ENTRY!r}
if not candidate.is_file():
    candidate = here / {ENTRY!r}
if not candidate.is_file():
    print(f"CORRECTNESS: FAIL -- no candidate at {{candidate}}")
    sys.exit(1)

command = [PYTHON, "-m", "evograd.adbench_tools", "evaluate", "--task", TASK, "--run-dir", RUN,
           "--origin", "geak", str(candidate)]
if "--correctness" in sys.argv[1:]:
    command.insert(-1, "--correctness-only")
proc = subprocess.run(command, capture_output=True, text=True)
try:
    report = json.loads(proc.stdout)
except json.JSONDecodeError:
    print("CORRECTNESS: FAIL -- evaluator produced no report")
    print(proc.stdout[-3000:] + proc.stderr[-3000:])
    sys.exit(1)

print(report["feedback"])
if not report["correct"]:
    print("CORRECTNESS: FAIL")
    sys.exit(1)
print("CORRECTNESS: PASS")
metrics = report["metrics"]
if "raw_forward_backward_full_step_ms" in metrics:
    case = {task.task_id!r}
    ours = metrics["raw_forward_backward_full_step_ms"]
    base = metrics["baseline_raw_full_step_ms"]
    print(f"Perf: baseline_ms={{base:.4f}} optimized_ms={{ours:.4f}} speedup={{base / ours:.4f}} ({{case}})")
    print(f"GEAK_RESULT_LATENCY_MS={{ours:.6f}} ({{case}})")
    print(f"GEAK_BASELINE_LATENCY_MS={{base:.6f}} ({{case}})")
    print(f"backward_from_saved_ms={{metrics['backward_from_saved_ms']:.4f}} "
          f"baseline_backward_ms={{metrics['baseline_latency_ms']:.4f}}")
    print(f"evograd combined_score={{metrics['combined_score']:.4f}} (the score this run is ranked by)")
sys.exit(0)
'''


def baseline_source(task) -> str:
    abi = task.spec["abi"]
    return f'''"""Frozen baseline: one eager PyTorch autograd step of {task.op_name} (do not edit).

reference_step(*args, *upstream_grads) -> (outputs..., input gradients...)
"""
import sys

sys.path.insert(0, {str(REPO / "src")!r})
import torch

from evograd.adbench_tools.task import load as _load
from evograd.opdecl.importing import resolve_callable as _resolve

_OP = _load({str(task.root)!r}).op()
_REFERENCE = _resolve(_OP.runtime_forward or _OP.forward)
_ARGS = {[a["name"] for a in abi["arguments"]]!r}
_ACTIVE = {{a.name: a.grad_name for a in _OP.active_args()}}
_GRAD_ORDER = {abi["grad_order"]!r}


def reference_step(*inputs):
    args = list(inputs[: len(_ARGS)])
    upstream = inputs[len(_ARGS):]
    leaves = {{}}
    for i, name in enumerate(_ARGS):
        if name in _ACTIVE:
            args[i] = args[i].detach().requires_grad_(True)
            leaves[_ACTIVE[name]] = args[i]
    with torch.enable_grad():
        out = _REFERENCE(*args)
        outs = tuple(out) if isinstance(out, (tuple, list)) else (out,)
        grads = torch.autograd.grad(outs, [leaves[g] for g in _GRAD_ORDER], upstream)
    return (*outs, *grads)
'''


def prepare(task, run_dir: Path, out: Path) -> Path:
    out = out.resolve()
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"{out} is not empty")
    (out / "baseline_src").mkdir(parents=True, exist_ok=True)
    (out / "kernel_src").mkdir(exist_ok=True)
    (out / "meta.json").write_text(json.dumps(meta(task, run_dir), indent=2) + "\n", encoding="utf-8")
    (out / "unittest.py").write_text(unittest_source(task, run_dir), encoding="utf-8")
    (out / "baseline_src" / "reference_step.py").write_text(baseline_source(task), encoding="utf-8")
    shutil.copy2(task.root / "TASK.md", out / "TASK.md")
    primitives = task.root / "adbench_primitives.py"
    if primitives.is_file():
        shutil.copy2(primitives, out / "adbench_primitives.py")
    (out / "kernel_src" / ".keep").write_text("", encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--task", type=Path, required=True)
    parser.add_argument("--run-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    from evograd.adbench_tools.task import load

    print(prepare(load(args.task), args.run_dir.resolve(), args.out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
